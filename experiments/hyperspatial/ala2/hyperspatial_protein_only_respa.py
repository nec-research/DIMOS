"""
Hyperspatial Replica Exchange for Alanine Dipeptide in Solvent (Protein-Only Penalty, RESPA).

Same as hyperspatial_protein_only.py, but every replica (separable and
non-separable alike) is integrated with a RESPA Langevin integrator instead
of plain LangevinDynamics. By default this sub-cycles the extra-dimension
penalty force n_inner times per outer timestep (HyperspatialRESPALangevinDynamics),
using a proper BAOAB ("VRORV") operator split, so the outer timestep can be
governed by the physical force field rather than by the (typically much stiffer)
penalty. With --exact-harmonic, the fast harmonic penalty is integrated
analytically (HyperspatialExactHarmonicRESPALangevinDynamics; requires
extra-dim-form harmonic).

For the separable replica (idx=0), the fast/slow force split is EXACT
(physical and extra-dimensional forces are already fully decoupled), so this
is exact subcycling. For the non-separable replicas, the split is
approximate since the base Hamiltonian couples physical and extra
coordinates through the generalized distance metric; see
HyperspatialRESPALangevinDynamics docstring for resonance caveats,
especially at the weak friction used here.

Usage:
    python hyperspatial_protein_only_respa.py [--num_extra_dim N] [--n_inner N] [--timestep DT]
    python hyperspatial_protein_only_respa.py --exact-harmonic [--timestep DT]

Example:
    python hyperspatial_protein_only_respa.py --n_inner 4
    python hyperspatial_protein_only_respa.py --timestep 2.0 --n_inner 8
    python hyperspatial_protein_only_respa.py --exact-harmonic --timestep 2.0
    python hyperspatial_protein_only_respa.py --friction 0.01

Output files:
- coordinates_*.pdb: Trajectories for each replica (3D projection)
- exchange_statistics.txt: Acceptance rates between replica pairs
- config.json: Simulation parameters
"""

