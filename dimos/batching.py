from warnings import warn


# This class implements the batching of several systems.
class MultiSys(MinimalSystem):
    def __init__(self, systems):
        super().__init__(systems[0].unit_system, systems[0].create_graph, systems[0].dtype, systems[0].dim)
        self.num_systems = len(systems)
        self.periodic = systems[0].periodic
        self.box = systems[0].box # TODO: Can this be different? Would be necessary for actually different systems!
        self.use_neighborlist = systems[0].use_neighborlist
        
        if hasattr(systems[0], "cutoff"):
            self.cutoff =  systems[0].cutoff

        self.systems = systems
        self.masses = torch.cat([sys.masses for sys in systems])

        self.start_index = [0]
        for sys in self.systems:
            self.start_index.append(self.start_index[-1]+sys.num_atoms)
        self.start_index.append(-1) # in case we need to loop until the end

        # First gather the different force contributions from the different systems and store in dictionary
        # We use (force_idx, type(force)) as the key to group corresponding forces across replicas
        self.bonded_force_components = []
        force_components = {}
        general_identical_force_components = {}
        for sys_idx, sys in enumerate(self.systems):
            for force_idx, force in enumerate(sys.bonded_force_components):
                # Use (force_idx, type) as key to match corresponding forces across replicas
                force_key = (force_idx, type(force))
                match force:
                    case HarmonicBond():
                        offset_bond_list = force.bond_list + self.start_index[sys_idx]
                        comp = force_components.setdefault(force_key, {
                            "bond_list": [],
                            "bond_parameters": [],
                            "force_template": force,
                        })
                        comp["bond_list"].append(offset_bond_list)
                        comp["bond_parameters"].append(force.bond_parameters)

                    case HarmonicAngle():
                        offset_edge_list_10 = force.edge_list_10 + self.start_index[sys_idx]
                        offset_edge_list_12 = force.edge_list_12 + self.start_index[sys_idx]
                        comp = force_components.setdefault(force_key, {
                            "offset_edge_list_10": [],
                            "offset_edge_list_12": [],
                            "angle_parameters": [],
                            "force_template": force,
                        })
                        comp["offset_edge_list_10"].append(offset_edge_list_10)
                        comp["offset_edge_list_12"].append(offset_edge_list_12)
                        comp["angle_parameters"].append(force.angle_parameters)

                    case Torsion():
                        offset_edge_list_1 = force.edge_list_1 + self.start_index[sys_idx]
                        offset_edge_list_2 = force.edge_list_2 + self.start_index[sys_idx]
                        offset_edge_list_3 = force.edge_list_3 + self.start_index[sys_idx]
                        comp = force_components.setdefault(force_key, {
                            "offset_edge_list_1": [],
                            "offset_edge_list_2": [],
                            "offset_edge_list_3": [],
                            "torsion_parameters": [],
                            "force_template": force,
                        })
                        comp["offset_edge_list_1"].append(offset_edge_list_1)
                        comp["offset_edge_list_2"].append(offset_edge_list_2)
                        comp["offset_edge_list_3"].append(offset_edge_list_3)
                        comp["torsion_parameters"].append(force.torsion_parameters)

                    case ExtraDimensionPenaltyEnergy():
                        pass  # handled separately below

                    case _:
                        #We check for sys_idx==0, as if all components are identical, then especially the first one also needs to be the same
                        if sys_idx == 0:
                            general_identical_force_components[force.__str__()] = force
                        else:
                            if force == general_identical_force_components.get(force.__str__(), None):
                                pass # Identical component, do nothing
                            else:
                                raise NotImplementedError("Encountered force component not implemented in force", force)

        for force in general_identical_force_components.values():
            warn(f"Found general identical force component: {force}. Adding this can be potentially dangerous. Please make sure your force correctly accepts batched inputs.")
            self.bonded_force_components.append(force)

        # Then make combined system taking care of all corresponding interactions
        for force_key, params in force_components.items():
            force_idx, force_type = force_key
            force = params["force_template"]
            match force:
                case HarmonicBond():
                    bond_list = torch.cat(params["bond_list"], dim=1)
                    bond_parameters = torch.cat(params["bond_parameters"])
                    self.bonded_force_components.append(
                        HarmonicBond(bond_list, bond_parameters, force.periodic, force.box)
                    )

                case HarmonicAngle():
                    angle_parameters = torch.cat(params["angle_parameters"])
                    force_contribution = HarmonicAngle(
                        torch.empty([3, 3]), angle_parameters, force.periodic, force.box
                    )
                    force_contribution.edge_list_10 = torch.cat(params["offset_edge_list_10"], dim=1)
                    force_contribution.edge_list_12 = torch.cat(params["offset_edge_list_12"], dim=1)
                    self.bonded_force_components.append(force_contribution)

                case Torsion():
                    torsion_parameters = torch.cat(params["torsion_parameters"])
                    force_contribution = Torsion(
                        torch.empty([4, 4]), torsion_parameters, force.periodic, force.box
                    )
                    force_contribution.edge_list_1 = torch.cat(params["offset_edge_list_1"], dim=1)
                    force_contribution.edge_list_2 = torch.cat(params["offset_edge_list_2"], dim=1)
                    force_contribution.edge_list_3 = torch.cat(params["offset_edge_list_3"], dim=1)
                    self.bonded_force_components.append(force_contribution)
                    
                case _:
                    pass

        # Handle the hyperspatial penalty energy components
        for IDX, force in enumerate(systems[0].bonded_force_components):
            if isinstance(force, ExtraDimensionPenaltyEnergy):
                penalty_extra_dim = torch.stack([torch.tensor(sys.bonded_force_components[IDX].penalty_extra_dim) for sys in self.systems])
                if force.mask is not None:
                    mask = torch.cat([force.mask for _ in range(self.num_systems)])
                    penalty_extra_dim = torch.repeat_interleave(penalty_extra_dim, repeats=self.systems[0].num_atoms)[mask].unsqueeze(1)
                    self.bonded_force_components.append(
                        ExtraDimensionPenaltyEnergy(
                            force.num_extra_dim,
                            penalty_extra_dim,
                            force.extra_box,
                            mask,
                            form=force.form,
                            k=force.k,
                        )
                    )
                else:
                    penalty_extra_dim = torch.repeat_interleave(penalty_extra_dim, repeats=self.systems[0].num_atoms).unsqueeze(1)
                    self.bonded_force_components.append(
                        ExtraDimensionPenaltyEnergy(
                            force.num_extra_dim,
                            penalty_extra_dim,
                            force.extra_box,
                            form=force.form,
                            k=force.k,
                        )
                    )


        # Build combined nonbonded components across simulations (mirrors your bonded pattern)
        self.nonbonded_force_components = []

        # Collect per-type contributions
        nb_components = {}

        for sys_idx, sys in enumerate(self.systems):
            for force in sys.nonbonded_force_components:
                start = self.start_index[sys_idx]

                match force:
                    case NonbondedInteractionsCutoff():
                        key = ("cutoff",)
                        comp = nb_components.setdefault(key, {
                            "sigmas": [],
                            "epsilons": [],
                            "charges": [],
                            "sigmas_adjust": [],
                            "epsilons_adjust": [],
                            "adjust_list": [],
                            "dihedral_exclusions": [],
                            # scalars / shared config
                            "cutoff": force.lj_energy_contrib.cutoff,
                            "switch_distance": force.lj_energy_contrib.switch_dist,
                            "scnb": force.lj_energy_contrib.scnb,
                            "scee": force.electrostatics_energy_contrib.scee,
                            "periodic": force.electrostatics_energy_contrib.periodic,
                            "box": force.electrostatics_energy_contrib.box,
                        })

                        comp["sigmas"].append(force.lj_energy_contrib.sigmas)
                        comp["epsilons"].append(force.lj_energy_contrib.epsilons)
                        comp["charges"].append(force.electrostatics_energy_contrib.charges)

                        # Optional adjustments; fall back to empty if not present
                        sa = getattr(force.lj_energy_contrib, "sigmas_adjust", None)
                        ea = getattr(force.lj_energy_contrib, "epsilons_adjust", None)
                        al = getattr(force.lj_energy_contrib, "adjust_list", None)
                        if sa is not None: comp["sigmas_adjust"].append(sa)
                        if ea is not None: comp["epsilons_adjust"].append(ea)
                        if al is not None:
                            # Offset adjust_list indices if it holds atom indices
                            comp["adjust_list"].append(al + start if al.numel() > 0 else al)

                        # 1-4 (dihedral) exclusions need index offset
                        d14 = force.lj_energy_contrib.exclusions_one_four
                        comp["dihedral_exclusions"].append(d14 + start)

