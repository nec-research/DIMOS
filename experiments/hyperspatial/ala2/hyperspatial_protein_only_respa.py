def make_hyperspatial_integrator(sys):
    """Create the RESPA or exact-harmonic RESPA Langevin integrator for a replica."""
    common = dict(
        timestep=config["timestep"],
        temperature=config["temperature"],
        friction=config["friction"],
        sys=sys,
        dtype=torch.float64,
    )
    if config["integrator"] == "exact_harmonic_respa":
        return HyperspatialExactHarmonicRESPALangevinDynamics(**common)
    return HyperspatialRESPALangevinDynamics(**common, n_inner=config["n_inner"])


