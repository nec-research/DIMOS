def log_statistics(step, batched_rex, num_replicas, mu_values, log_file, protein_mask, to_terminal=False):
    """Log intermediate statistics to terminal and file."""
    
    lines = []
    lines.append(f"\n{'='*80}")
    lines.append(f"Step {step + 1}/{config['n_steps']} ({100*(step+1)/config['n_steps']:.2f}%)")
    lines.append(f"Time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append(f"{'-'*80}")
    
    # Replica statistics
    lines.append("Replica Statistics:")
    lines.append(f"{'Replica':>8} {'mu':>10} {'Energy':>15} {'Prot ExtraRMS':>14} {'Solv ExtraRMS':>14}")
    lines.append(f"{'-'*70}")
    
    for idx in range(num_replicas):
        pos = batched_rex.get_pos(idx)
        energy = 0.0  # Use actual energy function if needed
        extra_coords = pos[:, 3:]
        
        # Separate RMS for protein and solvent
        prot_extra = extra_coords[protein_mask]
        solv_extra = extra_coords[~protein_mask]

        # TODO: Wrap distance periodically!
        prot_rms = torch.sqrt(torch.mean(prot_extra ** 2)).item() if prot_extra.numel() > 0 else 0.0
        solv_rms = torch.sqrt(torch.mean(solv_extra ** 2)).item() if solv_extra.numel() > 0 else 0.0
        
        if idx == 0:
            mu_label = f"{mu_values[0]:.2f}(S)"  # S for separable
        else:
            mu_label = f"{mu_values[idx-1]:.2f}"
        
        lines.append(f"{idx:>8} {mu_label:>10} {energy:>15.4f} {prot_rms:>14.4f} {solv_rms:>14.4f}")
    
    # Exchange statistics
    lines.append(f"\n{'-'*80}")
    lines.append("Exchange Statistics (cumulative):")
    lines.append(f"{'Pair':>10} {'Attempted':>12} {'Accepted':>12} {'Rate':>10}")
    lines.append(f"{'-'*50}")
    
    attempted = batched_rex.attempted_swaps
    accepted = batched_rex.accepted_swaps
    
    for i in range(len(attempted)):
        att = int(attempted[i].item())
        acc = int(accepted[i].item())
        rate = acc / att if att > 0 else 0.0
        lines.append(f"{i:>4}-{i+1:<4} {att:>12} {acc:>12} {rate:>10.4f}")
    
    # Calculate overall acceptance rate
    total_attempted = sum(attempted[i].item() for i in range(len(attempted)))
    total_accepted = sum(accepted[i].item() for i in range(len(accepted)))
    overall_rate = total_accepted / total_attempted if total_attempted > 0 else 0.0
    lines.append(f"{'-'*50}")
    lines.append(f"{'Overall':>10} {int(total_attempted):>12} {int(total_accepted):>12} {overall_rate:>10.4f}")
    
    lines.append(f"{'='*80}\n")
    
    # Output to terminal
    if to_terminal:
        for line in lines:
            print(line)
    
    # Append to log file
    with open(log_file, 'a') as f:
        for line in lines:
            f.write(line + "\n")

