def calc_3d_energy(batched_rex, idx):
    """
    Calculate energy using only 3D coordinates (projected Hamiltonian).
    
    For the separable system (idx=0), this simply evaluates the base 3D system
    energy since the neighborlist is already built from 3D coordinates.
    
    For non-separable systems (idx>0), we must rebuild the neighborlist from
    3D positions because the existing one was built from (3+D)-dim distances.
    Pairs within the 3D cutoff could be missing if their higher-dimensional
    distance exceeded the cutoff.
    """
    with torch.no_grad():
        pos = batched_rex.get_pos(idx).clone()
        pos_3d_padded = pos.clone()
        pos_3d_padded[:, 3:] = 0.0
        
        hyper_sys = batched_rex.simulations[idx].sys
        
        if hyper_sys.use_neighborlist:
            if idx == 0:
                # Separable system: neighborlist is already 3D-based, reuse it
                neighborlist = batched_rex.simulations[idx].neighborlist
            else:
                # Non-separable: rebuild neighborlist from 3D positions
                temp_idx = idx - 1
                neighborlist = batched_rex.batched_sim.neighbor_handlers[temp_idx].get_neighborlist(pos_3d_padded)
            energy = hyper_sys.calc_energy(pos_3d_padded, neighborlist)
        else:
            energy = hyper_sys.calc_energy(pos_3d_padded, None)
        
        return energy.item()

def calc_full_energy(batched_rex, idx):
    """
    Calculate full hyperspatial energy including extra dimensions.
    """
    with torch.no_grad():
        pos = batched_rex.get_pos(idx).clone()
        
        if batched_rex.simulations[idx].sys.use_neighborlist:
            if idx == 0:
                neighborlist = batched_rex.simulations[idx].neighborlist
            else:
                temp_idx = idx - 1
                neighborlist = batched_rex.batched_sim.neighborlist[temp_idx]
            energy = batched_rex.simulations[idx].sys.calc_energy(pos, neighborlist)
        else:
            energy = batched_rex.simulations[idx].sys.calc_energy(pos, None)
        
        return energy.item()

