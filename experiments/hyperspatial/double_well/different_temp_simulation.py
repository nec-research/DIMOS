"""
Parallel simulations of double-well system at different temperatures.

This script runs independent simulations (no replica exchange) at different
temperatures to compare sampling behavior. Useful as a baseline comparison
for parallel tempering.

Supports two modes:
- Standard mode: Individual simulations stepped separately
- Batched mode: Simulations batched together via MultiSim for better GPU utilization

Output files are compatible with analyze_plot_pt.py:
- trajectories_x.dat: x coordinates for each temperature
- energies.dat: potential energy for each temperature
- parameters.txt: simulation parameters including temperatures
- exchange_statistics.txt: placeholder (no exchanges, all zeros)
"""

import os
import math
from datetime import datetime
import torch

from dimos.simulation import MDSimulation
from dimos.integrators import LangevinDynamics
from dimos import constants
from dimos.batching import MultiSim

from double_well_system import DoubleWellSystem


class MultiTempRunner:
    """
    Runner for independent simulations of the double-well system at different temperatures.
    
    Unlike parallel tempering, no exchanges occur between replicas.
    This serves as a baseline comparison for enhanced sampling methods.
    
    Parameters
    ----------
    temperatures : list
        List of temperatures for the simulations (from low to high)
    a : float
        Double-well barrier height parameter
    b : float
        Double-well minima location parameter
    seed : int
        Random seed for reproducibility
    timestep : float
        Integration timestep
    friction : float
        Langevin friction coefficient
    batched : bool
        Whether to use MultiSim for batched simulation (better GPU utilization)
    """
    
    def __init__(
        self,
        temperatures: list = None,
        n_replicas: int = 8,
        T_min: float = 0.1,
        T_max: float = 0.5,
        a: float = 1.0,
        b: float = 1.0,
        seed: int = 42,
        timestep: float = 0.01,
        friction: float = 1.0,
        batched: bool = False,
    ):
        # Generate temperature ladder if not provided
        if temperatures is None:
            # Exponential temperature spacing (same as PT for fair comparison)
            temperatures = [
                T_min + (T_max - T_min) * (math.exp(float(i) / float(n_replicas - 1)) - 1.0) / (math.e - 1.0)
                for i in range(n_replicas)
            ]
        
        self.temperatures = temperatures
        self.n_replicas = len(temperatures)
        self.a = a
        self.b = b
        self.seed = seed
        self.timestep = timestep
        self.friction = friction
        self.batched = batched
        
        # Initialize constants for unitless system
        constants.init_constants_in_unit_system("unitless")
        
        # Create simulations at different temperatures
        self.simulations = []
        for idx, temp in enumerate(temperatures):
            system = DoubleWellSystem(
                n_particles=1,
                dim=1,
                a=a,
                b=b,
            )
            # Start at the left minimum
            initial_pos = torch.tensor([[-b]], requires_grad=True)
            integrator = LangevinDynamics(
                timestep=timestep,
                temperature=temp,
                friction=friction,
                sys=system
            )
            simulation = MDSimulation(
                sys=system,
                integrator=integrator,
                initial_pos=initial_pos,
                temperature=temp,
                seed=seed + idx
            )
            self.simulations.append(simulation)
        
        # Setup batched simulation if requested
        if batched:
            self.multi_sim = MultiSim(self.simulations, seed=seed)
        else:
            self.multi_sim = None
    
    def run(
        self,
        n_steps: int,
        save_interval: int = 100,
        output_dir: str = "output",
        verbose: bool = True,
    ):
        """
        Run independent simulations at different temperatures.
        
        Parameters
        ----------
        n_steps : int
            Total number of dynamics steps
        save_interval : int
            Interval at which to save coordinates and energies
        output_dir : str
            Directory for output files
        verbose : bool
            Whether to print progress information
        """
        # Create output directory with timestamp
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_path = os.path.join(output_dir, f"multitemp_{timestamp}")
        os.makedirs(output_path, exist_ok=True)

        # Save parameters (compatible with analyze_plot_pt.py)
        params_file = os.path.join(output_path, "parameters.txt")
        with open(params_file, 'w') as f:
            f.write(f"# Simulation parameters\n")
            f.write(f"temperatures = {self.temperatures}\n")
            f.write(f"n_replicas = {self.n_replicas}\n")
            f.write(f"a = {self.a}\n")
            f.write(f"b = {self.b}\n")
            f.write(f"timestep = {self.timestep}\n")
            f.write(f"friction = {self.friction}\n")
            f.write(f"steps_before_exchange = 0\n")  # No exchanges
            f.write(f"seed = {self.seed}\n")
            f.write(f"save_interval = {save_interval}\n")
            f.write(f"n_steps = {n_steps}\n")
            f.write(f"batched = {self.batched}\n")
            f.write(f"# Note: Independent simulations, no replica exchange\n")

        # Open output files
        trajectories_file = os.path.join(output_path, "trajectories_x.dat")
        output_file_x = open(trajectories_file, 'w')

        energy_file = os.path.join(output_path, "energies.dat")
        energy_output = open(energy_file, 'w')

        indices_file = os.path.join(output_path, "replica_indices.dat")
        indices_output = open(indices_file, 'w')
        
        # Run simulation
        for step in range(n_steps):
            # Step all simulations
            if self.batched:
                self.multi_sim.step(1, detach=True)
            else:
                for sim in self.simulations:
                    sim.step(1, detach=True)

            if step % save_interval == 0:
                # Save positions
                output_file_x.write(f"{step}\t")
                if self.batched:
                    for idx in range(self.n_replicas):
                        pos = self.multi_sim.get_pos(idx)
                        output_file_x.write(f"{pos[0, 0].item()}\t")
                else:
                    for sim in self.simulations:
                        output_file_x.write(f"{sim.pos[0, 0].item()}\t")
                output_file_x.write("\n")

                # Save energies
                energy_output.write(f"{step}\t")
                if self.batched:
                    for idx in range(self.n_replicas):
                        pos = self.multi_sim.get_pos(idx)
                        energy = self.simulations[idx].sys.calc_energy(pos, None)
                        energy_output.write(f"{energy.item()}\t")
                else:
                    for sim in self.simulations:
                        energy = sim.sys.calc_energy(sim.pos, None)
                        energy_output.write(f"{energy.item()}\t")
                energy_output.write("\n")

                # Save replica indices (constant for independent simulations)
                indices_output.write(f"{step}\t")
                for idx in range(self.n_replicas):
                    indices_output.write(f"{idx}\t")
                indices_output.write("\n")
                
                if verbose:
                    print(f"Step {step}/{n_steps}")
        
        # Close files
        output_file_x.close()
        energy_output.close()
        indices_output.close()
        
        # Write placeholder exchange statistics (compatible with analyze_plot_pt.py)
        self._write_placeholder_statistics(output_path)
        
        return output_path
    
    def _write_placeholder_statistics(self, output_path: str):
        """
        Write placeholder exchange statistics file for compatibility with analyze_plot_pt.py.
        Since no exchanges occur, all rates are 0.
        """
        stats_lines = []
        stats_lines.append("Final Exchange Statistics (Independent Simulations - No Exchanges):")
        stats_lines.append("-" * 60)
        
        for i in range(self.n_replicas - 1):
            stats_lines.append(f"Replica pair {i}-{i+1} (T={self.temperatures[i]:.4f} <-> T={self.temperatures[i+1]:.4f}):")
            stats_lines.append(f"    Attempted: 0")
            stats_lines.append(f"    Accepted:  0")
            stats_lines.append(f"    Rate:      0.0000")
        stats_lines.append("-" * 60)
        
        # Print to terminal
        print("\nIndependent simulations completed (no exchanges performed)")
        
        # Save to file
        stats_file = os.path.join(output_path, "exchange_statistics.txt")
